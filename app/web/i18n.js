  function langFromNavigator() {
    var value = '';
    try { value = String((navigator.language || navigator.userLanguage || 'en')).toLowerCase(); } catch (_) { value = 'en'; }
    if (value.indexOf('zh') === 0) return 'zh';
    if (value.indexOf('de') === 0) return 'de';
    if (value.indexOf('ar') === 0) return 'ar';
    if (value.indexOf('ru') === 0) return 'ru';
    return 'en';
  }

  function validLang(value) {
    return SUPPORTED.indexOf(String(value || '')) >= 0;
  }

  function storedLang() {
    try {
      var value = window.localStorage ? window.localStorage.getItem(STORAGE_KEY) : '';
      return validLang(value) ? value : '';
    } catch (_) { return ''; }
  }

  function translated(source) {
    if (!source || current === 'en') return null;
    var table = MESSAGES[current];
    if (!table || !Object.prototype.hasOwnProperty.call(table, source)) return null;
    return table[source];
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== 3 || !node.nodeValue) return;
    var parent = node.parentElement;
    if (!parent || parent.closest('[data-no-i18n]')) return;
    var tag = parent.tagName;
    if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT' || tag === 'TEXTAREA') return;
    if (!Object.prototype.hasOwnProperty.call(node, '__stitchOriginal')) {
      node.__stitchOriginal = node.nodeValue;
    }
    var source = node.__stitchOriginal;
    var trimmed = source.trim();
    if (!trimmed) return;
    var value = translated(trimmed);
    var next = value == null ? source : source.replace(trimmed, value);
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  var attributeStates = typeof WeakMap === 'function' ? new WeakMap() : null;
  function translateAttributes(element) {
    if (!element || element.nodeType !== 1 || !attributeStates) return;
    if (element.closest('[data-no-i18n]')) return;
    var states = attributeStates.get(element);
    if (!states) {
      states = {};
      attributeStates.set(element, states);
    }
    for (var i = 0; i < ATTRIBUTES.length; i += 1) {
      var name = ATTRIBUTES[i];
      if (!element.hasAttribute(name)) continue;
      var current = element.getAttribute(name);
      var state = states[name];
      if (!state) {
        state = states[name] = { original: current, rendered: null };
      } else if (state.rendered !== null && current !== state.rendered && current !== state.original) {
        // The app changed an attribute after localisation (e.g. a key placeholder).
        state.original = current;
        state.rendered = null;
      }
      var source = state.original;
      var trimmed = String(source || '').trim();
      if (!trimmed) continue;
      var value = translated(trimmed);
      var next = value == null ? source : String(source).replace(trimmed, value);
      if (current !== next) element.setAttribute(name, next);
      state.rendered = next;
    }
  }

  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) { translateTextNode(root); return; }
    if (root.nodeType === 1) translateAttributes(root);
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, null);
    var node = walker.nextNode();
    while (node) {
      if (node.nodeType === 3) translateTextNode(node);
      else translateAttributes(node);
      node = walker.nextNode();
    }
  }

  function applyDocument() {
    if (!document.body) return;
    var title = document.querySelector('title');
    if (title) {
      if (!originalTitle) originalTitle = title.textContent || '';
      var titleValue = translated(originalTitle.trim());
      title.textContent = titleValue == null ? originalTitle : titleValue;
    }
    walk(document.body);
  }

  function setLanguage(language) {
    var next = validLang(language) ? String(language) : 'en';
    current = next;
    if (document.documentElement) {
      document.documentElement.lang = next === 'zh' ? 'zh-CN' : next;
      document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.setAttribute('data-language', next);
      document.documentElement.classList.toggle('lang-ar', next === 'ar');
    }
    try {
      if (window.localStorage) window.localStorage.setItem(STORAGE_KEY, next);
    } catch (_) { /* private mode */ }
    var select = document.getElementById('language-select');
    if (select && select.value !== next) select.value = next;
    applyDocument();
    try {
      document.dispatchEvent(new CustomEvent('stitchcraft:language', { detail: { language: next } }));
    } catch (_) { /* old browser */ }
    return current;
  }

  function translate(value) {
    var text = String(value == null ? '' : value);
    if (current === 'en') return text;
    var table = MESSAGES[current];
    return table && Object.prototype.hasOwnProperty.call(table, text) ? table[text] : text;
  }

  function format(key, values) {
    var template = translate(key);
    return String(template).replace(/\{(\w+)\}/g, function (match, name) {
      return values && Object.prototype.hasOwnProperty.call(values, name) ? values[name] : match;
    });
  }

  function startObserver() {
    if (!window.MutationObserver || !document.body || observer) return;
    observer = new MutationObserver(function (mutations) {
      for (var i = 0; i < mutations.length; i += 1) {
        var added = mutations[i].addedNodes || [];
        for (var j = 0; j < added.length; j += 1) walk(added[j]);
      }
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  function init() {
    var language = storedLang() || langFromNavigator();
    if (!validLang(language)) language = 'en';
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', function () { setLanguage(language); startObserver(); }, { once: true });
    } else {
      setLanguage(language);
      startObserver();
    }
  }

